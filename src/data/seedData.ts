export function isPlanFeatureEnabled(
  planId: CenterSettings['currentPlanId'],
  flag: keyof PlanFeatureFlags
): boolean {
  const plan = getPlanConfig(planId);
  return Boolean(plan.featureFlags[flag]);
}

